package com.courier.common.dto;

import com.courier.common.enums.Channel;
import com.courier.common.enums.Priority;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.*;

import java.util.Map;

/*
 * This is the external contract - what the client sends to courier-api.
 * It must never change shape without a versioning strategy.
 * It is NOT the same as NotificationEvent (internal Kafka contract).
 *
 * Why separate?
 * - The client doesn't know about eventId, sourceService, timestamp.
 *   Those are internal fields generated by courier-api.
 * - If you change the Kafka event format, clients are unaffected.
 * - If a client changes their request format, your internal
 *   event format stays stable.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class NotificationRequest {

    /*
     * correlationId is the client's idempotency key.
     * The client generates this. If they send the same
     * correlationId twice, they get the same response both times.
     * Convention: use a UUID or a domain-meaningful ID
     * like "order-789-shipped-notification".
     */
    @NotBlank(message = "correlationId must not be blank")
    @Size(max = 255, message = "correlationId must not exceed 255 characters")
    private String correlationId;

    @NotNull(message = "channel must not be null")
    private Channel channel;

    @NotBlank(message = "recipient must not be blank")
    @Size(max = 500, message = "recipient must not exceed 500 characters")
    private String recipient;

    @Size(max = 1000, message = "subject must not exceed 1000 characters")
    private String subject;

    @NotBlank(message = "content must not be blank")
    private String content;

    @Builder.Default
    private Priority priority = Priority.NORMAL;

    /*
     * Flexible key-value pairs for channel-specific data.
     * EMAIL might use: {"from": "noreply@courier.io", "replyTo": "support@co.io"}
     * WEBHOOK might use: {"hmacSecret": "...", "timeoutMs": "5000"}
     * Not queried - stored as-is.
     */
    private Map<String, String> metadata;
}