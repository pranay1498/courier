package com.courier.worker.service;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.data.redis.core.RedisTemplate;
import org.springframework.stereotype.Service;

import java.time.Duration;

@Service
@RequiredArgsConstructor
@Slf4j
public class DeduplicationService {

    private final RedisTemplate<String, String> redisTemplate;

    /*
     * 24 hours TTL.
     * Kafka's default log retention is 7 days (168 hours).
     * In theory, a message could be redelivered up to 7 days later.
     * 24 hours covers the realistic redelivery window while keeping
     * Redis memory usage bounded.
     *
     * If you're worried about redelivery beyond 24 hours,
     * extend the TTL - the memory cost is one small string per event.
     */
    private static final Duration DEDUP_TTL = Duration.ofHours(24);

    /*
     * Returns true if this eventId is a DUPLICATE (already processed).
     * Returns false if this eventId is NEW (should be processed, was failed).
     *
     * Why eventId and not correlationId?
     * correlationId is the client's idempotency key - handled at the
     * API layer. eventId is generated by the API for each Kafka publish
     * - it's the internal event identity. Dedup at the consumer level
     * uses eventId because the same notification could theoretically
     * be re-published (replay from PENDING status) with a new eventId.
     */
    public boolean isDuplicate(String eventId) {
        String key = getDedupKey(eventId);
        boolean isDuplicate = redisTemplate.hasKey(key);

        if (isDuplicate) {
            log.warn("Duplicate event detected - skipping. eventId={}", eventId);
        }
        return isDuplicate;
    }

    /*
     * Mark as processed - called ONLY after successful delivery.
     * Now retries are not blocked by a failed first attempt.
     *
     */
    public void markProcessed(String eventId) {
        String key = getDedupKey(eventId);
        redisTemplate.opsForValue().set(key, "processed", DEDUP_TTL);
        log.debug("Event marked as processed. eventId={}", eventId);
    }

    private String getDedupKey(String eventId){
        return "dedup:" + eventId;
    }
}